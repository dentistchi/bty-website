-- Read-only catalog export for the reward-fence PostgREST harness. Reads pg_catalog
-- only: no table row, auth user or learner record is selected. Run with
--   supabase db query --linked -f scripts/qa/reward-fence-prod-schema-export.sql
-- and assemble with scripts/qa/reward-fence-prod-schema-assemble.mjs.
with tabs as (
  select c.oid, c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r' and c.relname = any (array[
    'arena_profiles','arena_runs','arena_events','weekly_xp','arena_weekly_quest_claims','core_xp_ledger',
    'train_day_completions','user_healing_awakening_acts','user_healing_milestones','user_advanced_unlocks',
    'foundry_events','foundry_event_participants','foundry_event_training_progress','foundry_event_participation_mode',
    'foundry_event_assignments','foundry_event_assignment_audit','foundry_participant_followups',
    'foundry_participant_followup_audit','foundry_participant_apply_windows','foundry_event_quiz_attempts',
    'bty_organizations','bty_org_memberships','activity_xp_events','arena_leagues','bty_action_contracts'])
),
named_fns as (
  select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.proname = any (array[
    'increment_arena_xp','increment_weekly_xp','ensure_arena_profile','bty_foundry_award_daily_capped',
    'bty_foundry_claim_assignment','bty_foundry_materialize_followup','bty_foundry_materialize_apply_window',
    'bty_foundry_redeem_completion_claim','run_season_carryover'])
),
dep_fns as (
  -- Functions that defaults, checks, policies or triggers of the exported tables depend on.
  select distinct d.refobjid as oid from pg_depend d
  where d.refclassid = 'pg_proc'::regclass and (
    (d.classid = 'pg_attrdef'::regclass and d.objid in (select oid from pg_attrdef where adrelid in (select oid from tabs)))
    or (d.classid = 'pg_constraint'::regclass and d.objid in (select oid from pg_constraint where conrelid in (select oid from tabs)))
    or (d.classid = 'pg_policy'::regclass and d.objid in (select oid from pg_policy where polrelid in (select oid from tabs)))
    or (d.classid = 'pg_trigger'::regclass and d.objid in (select oid from pg_trigger where tgrelid in (select oid from tabs) and not tgisinternal)))
),
fns as (
  select p.oid from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where p.oid in (select oid from named_fns union select oid from dep_fns) and n.nspname = 'public'
),
enum_types as (
  select distinct t.oid from tabs join pg_attribute a on a.attrelid = tabs.oid and a.attnum > 0 and not a.attisdropped
  join pg_type t on t.oid = a.atttypid where t.typtype = 'e'
),
seqs as (
  select distinct s.oid, s.relname from tabs join pg_depend d on d.refobjid = tabs.oid and d.classid = 'pg_class'::regclass
  join pg_class s on s.oid = d.objid and s.relkind = 'S'
),
priv(name, ord) as (values ('SELECT',1),('INSERT',2),('UPDATE',3),('DELETE',4),('TRUNCATE',5),('REFERENCES',6),('TRIGGER',7))
select 10 as section, t.typname as name,
  format('create type public.%I as enum (%s);', t.typname,
    (select string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) from pg_enum e where e.enumtypid = t.oid)) as ddl
from pg_type t where t.oid in (select oid from enum_types)
union all
select 20, s.relname, format('create sequence if not exists public.%I;', s.relname) from seqs s
union all
select 30, tabs.relname, format('create table public.%I (%s);', tabs.relname, (
  select string_agg(format('%I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
    case when a.attidentity = 'a' then ' generated always as identity' when a.attidentity = 'd' then ' generated by default as identity' else '' end
    || coalesce(' default ' || pg_get_expr(d.adbin, d.adrelid), ''),
    case when a.attnotnull then ' not null' else '' end), ', ' order by a.attnum)
  from pg_attribute a left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
  where a.attrelid = tabs.oid and a.attnum > 0 and not a.attisdropped)) from tabs
union all
-- Primary/unique/check first; FKs only when the referenced table is exported or auth.users.
select case when con.contype = 'f' then 50 else 40 end, tabs.relname || '.' || con.conname,
  format('alter table public.%I add constraint %I %s;', tabs.relname, con.conname, pg_get_constraintdef(con.oid))
from tabs join pg_constraint con on con.conrelid = tabs.oid
where con.contype in ('p','u','c','x') or (con.contype = 'f' and (con.confrelid in (select oid from tabs) or con.confrelid = 'auth.users'::regclass))
union all
select 55, tabs.relname || '.' || con.conname, format('-- omitted FK outside export: %s', pg_get_constraintdef(con.oid))
from tabs join pg_constraint con on con.conrelid = tabs.oid
where con.contype = 'f' and con.confrelid not in (select oid from tabs) and con.confrelid <> 'auth.users'::regclass
union all
select 60, i.indexname, i.indexdef || ';' from pg_indexes i
where i.schemaname = 'public' and i.tablename in (select relname from tabs)
  and i.indexname not in (select conname from pg_constraint where conrelid in (select oid from tabs) and contype in ('p','u','x'))
union all
select 70, p.oid::regprocedure::text, pg_get_functiondef(p.oid) || ';' from pg_proc p where p.oid in (select oid from fns)
union all
select 75, p.oid::regprocedure::text,
  format('revoke all on function %s from public;', p.oid::regprocedure) || coalesce((
    select string_agg(format(' grant execute on function %s to %I;', p.oid::regprocedure, r.rolname), '')
    from aclexplode(p.proacl) x join pg_roles r on r.oid = x.grantee
    where x.privilege_type = 'EXECUTE' and r.rolname in ('anon','authenticated','service_role')), '')
from pg_proc p where p.oid in (select oid from fns)
union all
select 80, tabs.relname, format('alter table public.%I enable row level security;', tabs.relname)
  || case when c.relforcerowsecurity then format(' alter table public.%I force row level security;', tabs.relname) else '' end
from tabs join pg_class c on c.oid = tabs.oid where c.relrowsecurity
union all
select 85, pol.tablename || '.' || pol.policyname,
  format('create policy %I on public.%I as %s for %s to %s%s%s;', pol.policyname, pol.tablename, lower(pol.permissive), lower(pol.cmd),
    (select string_agg(quote_ident(r), ', ') from unnest(pol.roles) r),
    coalesce(' using (' || pol.qual || ')', ''), coalesce(' with check (' || pol.with_check || ')', ''))
from pg_policies pol where pol.schemaname = 'public' and pol.tablename in (select relname from tabs)
union all
select 90, tabs.relname, (
  select string_agg(format('grant %s on public.%I to %I;', x.privs, tabs.relname, x.rolname), ' ')
  from (select r.rolname, string_agg(e.privilege_type, ', ' order by pv.ord) privs
        from aclexplode((select relacl from pg_class where oid = tabs.oid)) e join pg_roles r on r.oid = e.grantee
        join priv pv on pv.name = e.privilege_type
        where r.rolname in ('anon','authenticated','service_role') group by r.rolname) x) from tabs
union all
select 91, tabs.relname || '.' || a.attname, (
  select string_agg(format('grant %s (%I) on public.%I to %I;', e.privilege_type, a.attname, tabs.relname, r.rolname), ' ')
  from aclexplode(a.attacl) e join pg_roles r on r.oid = e.grantee where r.rolname in ('anon','authenticated','service_role'))
from tabs join pg_attribute a on a.attrelid = tabs.oid and a.attacl is not null and a.attnum > 0
union all
select 92, s.relname, format('grant usage, select on sequence public.%I to authenticated, service_role;', s.relname) from seqs s
union all
select 95, tabs.relname || '.' || t.tgname, pg_get_triggerdef(t.oid) || ';' from tabs join pg_trigger t on t.tgrelid = tabs.oid and not t.tgisinternal
order by 1, 2;
